function Figure({ look }) {
  const top = look.top.color;
  const pants = look.pants || PANTS; // 군복·수형복은 바지·신발 색도 바꿈 (없으면 기본)
  const shoe = look.shoe || SHOE;
  const long = look.hair && look.hair.style === 'long';
  const ride = !!look.ride;
  return (
    <svg className="v-fig" viewBox="0 -2 18 27" width="25" height="37" style={{ overflow: 'visible' }} shapeRendering="crispEdges" aria-hidden="true">
      {/* 긴 머리 뒷부분 (얼굴·몸 뒤로 양옆만 보임) */}
      {long && <><P x={1} y={6} w={16} h={8} c={OUT} /><P x={2} y={7} w={14} h={6} c={look.hair.color} /></>}
      {/* 다리 (fb: 왼다리 / fa: 오른다리) - 탈것 탑승 중에는 탈것과 옆모습 탑승 다리가 대신 그려짐 */}
      {!ride && <g className="fb leg"><P x={5} y={20} w={4} h={5} c={OUT} /><P x={6} y={21} w={2} h={2} c={pants} /><P x={6} y={23} w={2} c={shoe} /></g>}
      {!ride && <g className="fa leg"><P x={9} y={20} w={4} h={5} c={OUT} /><P x={10} y={21} w={2} h={2} c={pants} /><P x={10} y={23} w={2} c={shoe} /></g>}
      {/* 팔: 탈것 탑승 중에는 핸들·고삐·운전대를 잡으러 앞으로 뻗은 옆모습 팔, 평소에는 양옆 팔 */}
      {!ride && (
        <>
          <g className="fa arm"><P x={2} y={13} w={2} h={7} c={OUT} /><P x={1} y={14} w={4} h={5} c={OUT} /><P x={2} y={14} w={2} h={3} c={top} /><P x={2} y={17} w={2} h={2} c={SKIN} /></g>
          <g className="fb arm"><P x={14} y={13} w={2} h={7} c={OUT} /><P x={13} y={14} w={4} h={5} c={OUT} /><P x={14} y={14} w={2} h={3} c={top} /><P x={14} y={17} w={2} h={2} c={SKIN} /></g>
        </>
      )}
      <Top {...look.top} />
      {look.ride && <Ride {...look.ride} pants={pants} shoe={shoe} />}
      {ride && (
        <g className="fa arm">
          <P x={9} y={13} w={7} h={4} c={OUT} />
          <P x={10} y={14} w={4} h={2} c={top} />
          <P x={14} y={14} w={2} h={2} c={SKIN} />
        </g>
      )}
      {/* 얼굴 */}
      <S rows={HEAD_OUT} c={OUT} />
      <S rows={HEAD_SKIN} c={SKIN} />
      {look.hair ? <Hair {...look.hair} /> : <P x={9} y={1} c="#3a2c26" />}
      {/* 눈 (세로 2칸) + 볼터치: 탈것 탑승 시 진행 방향(오른쪽 옆모습)을 바라봄 */}
      {ride ? (
        <>
          <P x={9} y={7} h={2} c={OUT} /><P x={13} y={7} h={2} c={OUT} />
          <P x={7} y={9} c={CHEEK} /><P x={14} y={9} c={CHEEK} />
        </>
      ) : (
        <>
          <P x={6} y={7} h={2} c={OUT} /><P x={11} y={7} h={2} c={OUT} />
          <P x={4} y={9} c={CHEEK} /><P x={13} y={9} c={CHEEK} />
        </>
      )}
      {look.hat && <Hat {...look.hat} />}
    </svg>
  );
}

export default Figure;
